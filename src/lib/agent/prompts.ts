export const DEMO_TEMPLATES = [
  "Расскажи про артикул {SKU_IN}: есть в наличии, какие характеристики, есть ли сертификат?",
  "А {SKU_OUT} есть? Если нет — что посоветуешь взамен и почему?",
  "Какие условия оплаты и доставки?",
  "Добавь {SKU_IN} в корзину, 2 штуки",
  "Да, добавь",
];

export function fillDemoPrompts(skuIn: string, skuOut: string): string[] {
  return DEMO_TEMPLATES.map((t) =>
    t.replace("{SKU_IN}", skuIn || "—").replace("{SKU_OUT}", skuOut || "—"),
  );
}
